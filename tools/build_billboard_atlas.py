"""Build the billboard atlas from the ad pack in assets/billboards.

  assets/billboards/*.png -> textures/billboards.jpg (one 16:9 cell per ad)

and writes js/billboards.js with where each ad sits and its brand, so js/city.js can put
every ad in the pack on the city's screens. The ads (1672 x 940 or 941, about 16:9) are
scaled into cells of CELL_W x CELL_H on a COLS-wide grid, each with PAD pixels of its own
edge repeated around it, so mipmaps never pull in a neighbor.

Run from the repository root:  python3 tools/build_billboard_atlas.py
"""
import json, os
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'billboards')
OUT = os.path.join(ROOT, 'textures', 'billboards.jpg')
COLS, CELL_W, CELL_H, PAD = 8, 512, 288, 4


def main():
  manifest = {e['filename']: e['brand'] for e in json.load(open(os.path.join(SRC, 'manifest.json'), encoding='utf-8'))}
  files = sorted(f for f in os.listdir(SRC) if f.endswith('.png'))
  rows = -(-len(files) // COLS)
  sheet = np.zeros((rows * CELL_H, COLS * CELL_W, 3), np.uint8)
  iw, ih = CELL_W - 2 * PAD, CELL_H - 2 * PAD
  cells = []
  for i, f in enumerate(files):
    im = Image.open(os.path.join(SRC, f)).convert('RGB')
    # Crop to the cell's shape (a few px off the top and bottom), then scale into it
    w, h = im.size
    ch = round(w * ih / iw)
    if ch <= h: im = im.crop((0, (h - ch) // 2, w, (h - ch) // 2 + ch))
    else:
      cw = round(h * iw / ih)
      im = im.crop(((w - cw) // 2, 0, (w - cw) // 2 + cw, h))
    a = np.asarray(im.resize((iw, ih), Image.LANCZOS))
    a = np.pad(a, ((PAD, PAD), (PAD, PAD), (0, 0)), mode='edge')
    x, y = (i % COLS) * CELL_W, (i // COLS) * CELL_H
    sheet[y:y + CELL_H, x:x + CELL_W] = a
    cells.append({'rect': [x + PAD, y + PAD, iw, ih], 'brand': manifest.get(f, f[:-4])})
  Image.fromarray(sheet).save(OUT, quality=88, optimize=True, progressive=True)
  W, H = COLS * CELL_W, rows * CELL_H

  L = []
  L.append('// Generated by tools/build_billboard_atlas.py from assets/billboards. Do not edit by hand.')
  L.append('// The billboard ads: one page of the city atlases, and where each ad sits on it.')
  L.append("import { ATLASES } from './cityTiles.js';")
  L.append('')
  L.append(f'ATLASES.billboards = {{ url: "textures/billboards.jpg", w: {W}, h: {H} }};')
  L.append('')
  L.append('// Each ad: [x, y, w, h] px on the page and its brand')
  L.append('export const BILLBOARDS = [')
  for c in cells:
    L.append(f"  [{', '.join(map(str, c['rect']))}, {json.dumps(c['brand'])}],")
  L.append('];')
  with open(os.path.join(ROOT, 'js', 'billboards.js'), 'w', encoding='utf-8') as f:
    f.write('\n'.join(L) + '\n')
  print(f'{len(cells)} ads -> {W} x {H}, {os.path.getsize(OUT) // 1024} KB')


if __name__ == '__main__':
  main()
